# Sets 

# empty set 
empty_set = {} # This is Dictionary, Empty Set Cannot be created with {}
print(type(empty_set))
print(empty_set)

# empty set 
empty_set = set()
print(type(empty_set))
print(empty_set)

# Set with Numeric Data 
data = {10,20,30,40,30,20,50}
print(type(data))
print(data)

# Set with Mixed Data 
data = {10,30,20,30,30,"python","ai",5.5,True}
print(data)

